#!/usr/bin/env node
/**
 * typecheck-baseline.mjs — TypeScript error ratchet.
 *
 * The frontend has a large PRE-EXISTING TypeScript error surface. `npm run
 * typecheck` reports all of it and exits non-zero, which used to make CI red on
 * every push and — because `lint-and-typecheck` gates `build` and `deploy` —
 * blocked shipping entirely.
 *
 * This script keeps the check meaningful instead of switching it off:
 *
 *   * it runs the real compiler (TypeScript resolved from this package, so it
 *     never falls back to the unrelated `tsc` npm placeholder);
 *   * it counts errors PER FILE and compares them to `typecheck-baseline.json`;
 *   * it FAILS only when the debt GROWS — a new error, an existing file with
 *     more errors, or a brand-new file that has errors;
 *   * it PASSES when the count drops, and tells you to refresh the baseline.
 *
 * So CI blocks on type errors *you introduce* and tolerates the known ones.
 *
 * Usage:
 *   node scripts/typecheck-baseline.mjs            # check against the baseline
 *   node scripts/typecheck-baseline.mjs --update   # rewrite the baseline
 */

import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const FRONTEND_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BASELINE_PATH = join(FRONTEND_DIR, 'typecheck-baseline.json');
const UPDATE = process.argv.includes('--update');

// ── Resolve the REAL TypeScript, never the `tsc` placeholder package ─────────
let tscBin;
let tsVersion = 'unknown';
try {
  const pkgPath = require.resolve('typescript/package.json', { paths: [FRONTEND_DIR] });
  tsVersion = JSON.parse(readFileSync(pkgPath, 'utf8')).version;
  tscBin = join(dirname(pkgPath), 'bin', 'tsc');
} catch (err) {
  console.error('FATAL: TypeScript is not installed in this workspace.');
  console.error('       Install it with `pnpm install` (frontend devDependency "typescript").');
  process.exit(2);
}

console.log(`TypeScript ${tsVersion}  ->  ${tscBin.replace(FRONTEND_DIR + '\\', '')}`);
console.log('Running tsc --noEmit (this takes a minute)…\n');

const run = spawnSync(process.execPath, [tscBin, '--noEmit'], {
  cwd: FRONTEND_DIR,
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
  shell: false,
});

const output = `${run.stdout || ''}\n${run.stderr || ''}`;

// tsc reports "path(line,col): error TSxxxx: message". Count per FILE so an
// error moving between files is not mistaken for new debt.
const DIAG = /^(.+?)\(\d+,\d+\): error TS\d+:/gm;
const perFile = new Map();
let match;
while ((match = DIAG.exec(output)) !== null) {
  const file = match[1].replace(/\\/g, '/').trim();
  perFile.set(file, (perFile.get(file) || 0) + 1);
}

const total = [...perFile.values()].reduce((a, b) => a + b, 0);

// A compiler that produced nothing at all means it did not actually run. That
// must never be mistaken for "clean".
if (run.error || (run.status !== 0 && total === 0)) {
  console.error('FATAL: the TypeScript compiler did not produce diagnostics.');
  if (run.error) console.error(run.error.message);
  else console.error(output.trim().split('\n').slice(0, 20).join('\n'));
  process.exit(2);
}

console.log(`Files with errors: ${perFile.size}`);
console.log(`Total errors:      ${total}\n`);

if (UPDATE) {
  const payload = {
    _comment:
      'Generated by `npm run typecheck:baseline -- --update`. ' +
      'Error count per file. The ratchet fails when this grows.',
    generatedAt: new Date().toISOString(),
    typescriptVersion: tsVersion,
    totalErrors: total,
    files: Object.fromEntries([...perFile.entries()].sort(([a], [b]) => a.localeCompare(b))),
  };
  writeFileSync(BASELINE_PATH, JSON.stringify(payload, null, 2) + '\n', 'utf8');
  console.log(`Baseline written: ${BASELINE_PATH.replace(FRONTEND_DIR + '\\', '')}`);
  console.log(`Total errors recorded: ${total}`);
  process.exit(0);
}

if (!existsSync(BASELINE_PATH)) {
  console.error(`FATAL: baseline not found: ${BASELINE_PATH}`);
  console.error('       Create it once with:  npm run typecheck:baseline -- --update');
  process.exit(2);
}

const baseline = JSON.parse(readFileSync(BASELINE_PATH, 'utf8'));
const baseFiles = baseline.files || {};
const baseTotal = Number(baseline.totalErrors || 0);

if (baseline.typescriptVersion && baseline.typescriptVersion !== tsVersion) {
  console.warn(
    `NOTE: baseline was recorded with TypeScript ${baseline.typescriptVersion}, ` +
    `running ${tsVersion}. Diagnostics can differ between compiler versions;` +
    '\n      if the comparison below looks wrong, refresh with: npm run typecheck:baseline -- --update\n',
  );
}

// ── Compare ─────────────────────────────────────────────────────────────────
const regressions = [];
const improvements = [];

for (const [file, count] of perFile) {
  const before = Number(baseFiles[file] || 0);
  if (count > before) regressions.push({ file, before, after: count });
  else if (count < before) improvements.push({ file, before, after: count });
}

// A file that was previously clean but now has errors is a regression too; the
// loop above already catches it (before = 0). A file that no longer exists is
// only reported as an improvement.
for (const [file, before] of Object.entries(baseFiles)) {
  if (!perFile.has(file)) improvements.push({ file, before, after: 0 });
}

if (regressions.length === 0) {
  const delta = total - baseTotal;
  console.log('PASS — no new TypeScript errors.');
  if (improvements.length > 0) {
    console.log(`\n${improvements.length} file(s) improved (${delta <= 0 ? delta : '+' + delta} errors overall).`);
    console.log('Refresh the baseline to lock in the win:');
    console.log('  npm run typecheck:baseline -- --update');
  } else {
    console.log(`Error count unchanged at ${total}.`);
  }
  process.exit(0);
}

console.error('FAIL — TypeScript debt grew.\n');
for (const r of regressions.sort((a, b) => (b.after - b.before) - (a.after - a.before))) {
  console.error(`  ${r.file}: ${r.before} -> ${r.after}  (+${r.after - r.before})`);
}
console.error(`\nTotal: ${baseTotal} -> ${total}  (+${total - baseTotal})`);
console.error('\nFix the errors above, or — only if the new errors are legitimate and you ' +
  'intend to accept them — refresh the baseline:');
console.error('  npm run typecheck:baseline -- --update');
process.exit(1);