// ─── Customer Statement (ERP-authoritative PDF) ─────────────────────────────
//
// Generates an OFFICIAL customer account statement PDF from the ERP's
// authoritative ledger (customerLedger.cjs). The statement is a READ-ONLY
// representation — it MUST NOT create transactions, modify balances, or
// write ledger records.
//
// Period contract: ?from=YYYY-MM-DD&to=YYYY-MM-DD (optional).
// Defaults to the last 365 days when no period is specified.
router.get('/customers/statement/document', async (req, res) => {
  try {
    const { id, customer_id } = req.portalUser;
    let { from, to } = req.query || {};

    // Default period: last 365 days.
    if (!from || !to) {
      const now = new Date();
      const end = now.toISOString().split('T')[0];
      const start = new Date(now.getTime() - 365 * 86400000).toISOString().split('T')[0];
      from = from || start;
      to = to || end;
    }

    // Statement data is fetched from the authoritative portal service
    // (which uses customerLedger.buildLedger internally).
    const statementsData = await portalService.getStatements(customer_id, from, to);
    if (!statementsData) {
      return res.status(404).json({ error: 'Statement data not found' });
    }

    // Attach period metadata for the renderer.
    statementsData.startDate = from;
    statementsData.endDate = to;

    // Gated + audited download marker (best-effort).
    try {
      await portalLifecycleService.recordDownload({
        docType: 'statement',
        docId: `statement_${customer_id}_${from}_${to}`,
        portalUserId: id,
        customerId: customer_id,
        context: requestContext(req),
      });
    } catch (_) { /* audit is best-effort; never blocks an authorized download */ }

    const ownerCustomer = await repoCanonical.getById('customers', customer_id).catch(() => null);
    const statementData = portalService.buildStatementData(customer_id, ownerCustomer, statementsData);

    const { buffer } = await officialDocumentService.renderOfficialPdf({
      type: 'ACCOUNT_STATEMENT',
      rawData: statementData,
      customers: ownerCustomer ? [ownerCustomer] : [],
      channel: 'portal',
    });

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', officialDocumentService.buildContentDisposition(
      `Statement-${statementData.customerName}_${from}_to_${to}.pdf`
    ));
    res.setHeader('Cache-Control', 'no-store');
    return res.status(200).send(buffer);
  } catch (err) {
    if (err.code === 'RENDERER_UNAVAILABLE') {
      console.error('[Portal] Official document renderer not configured:', err.message);
      return res.status(503).json({ error: 'official_document_renderer_unconfigured' });
    }
    console.error('[Portal] Official statement document failed:', err.message);
    return res.status(500).json({ error: 'official_document_generation_failed' });
  }
});

