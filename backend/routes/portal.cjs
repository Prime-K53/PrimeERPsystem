// ─── Official document downloads (ERP-authoritative PDF) ────────────────────
//
// Streams the OFFICIAL document generated by the ERP's own renderer
// (PrimeDocument pipeline) for records the authenticated customer owns.
//   - Customer identity: portal JWT only; the record is fetched through the
//     existing customer-scoped getters, so foreign ids resolve to NOT_FOUND
//     (existence is never leaked across customers).
//   - Transport: Option A — application/pdf bytes with Content-Disposition.
//   - Audit: reuses the gated download audit trail (best-effort).
async function sendOfficialDocument(req, res, { docType, fetchRecord, resolveFilename, renderType }) {
  try {
    const { id, customer_id } = req.portalUser;
    const record = await fetchRecord(id, customer_id);
    if (!record) {
      return res.status(404).json({ error: 'Document not found' });
    }

    // Gated + audited download marker (same audit trail as /downloads).
    try {
      await portalLifecycleService.recordDownload({
        docType,
        docId: record.id || id,
        portalUserId: id,
        customerId: customer_id,
        context: requestContext(req),
      });
    } catch (_) { /* audit is best-effort; never blocks an authorized download */ }

    const ownerCustomer = await repoCanonical.getById('customers', customer_id).catch(() => null);
    const { buffer } = await officialDocumentService.renderOfficialPdf({
      type: renderType,
      rawData: record,
      customers: ownerCustomer ? [ownerCustomer] : [],
      channel: 'portal',
    });

    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', officialDocumentService.buildContentDisposition(resolveFilename(record)));
    res.setHeader('Cache-Control', 'no-store');
    return res.status(200).send(buffer);
  } catch (err) {
    if (err.code === 'RENDERER_UNAVAILABLE') {
      console.error('[Portal] Official document renderer not configured:', err.message);
      return res.status(503).json({ error: 'official_document_renderer_unconfigured' });
    }
    console.error(`[Portal] Official ${docType} document failed:`, err.message);
    return res.status(500).json({ error: 'official_document_generation_failed' });
  }
}

